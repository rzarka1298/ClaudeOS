#!/usr/bin/env node
// Regenerates `docs/design/prototypes/fixtures.js` from the single synthetic
// source `packages/test-fixtures/src/widget-fixtures.json` (UI-01, D-05).
//
// This script is the ONLY sanctioned way that file changes. It exists for one
// reason: a `file://` page cannot `readFile` or request a local JSON file, so
// the prototypes need the same data as an assignable browser global. Two
// copies of a fixture is exactly the situation where a hand-edit lands in one
// and not the other, and the copy that ends up in a committed screenshot
// baseline is the one nobody re-reads. So the copy is generated, and the
// regeneration is a committed gate:
//
//   node scripts/generate-prototype-fixtures.mjs && git diff --exit-code -- docs/design/prototypes/fixtures.js
//
// A non-empty diff means the JSON moved and the browser copy did not --
// which, once plan 03-09 reuses this fixture as the visual-regression input,
// is the difference between a screenshot that proves something and one that
// proves the fixture is stale.
//
// Deliberately dependency-free and deliberately non-rebuilding: it reads a
// checked-in JSON file and writes a string. There is no build step to shell
// out to, so "the fixture is stale" can never be confused with "the build is
// stale" (the failure mode scripts/generate-example-vault.mjs guards against
// by failing loud instead).
//
// Usage:
//   node scripts/generate-prototype-fixtures.mjs               # write the committed copy
//   node scripts/generate-prototype-fixtures.mjs --out <path>  # write elsewhere (the determinism test)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(repoRoot, "packages", "test-fixtures", "src", "widget-fixtures.json");
const defaultOutPath = join(repoRoot, "docs", "design", "prototypes", "fixtures.js");

const args = process.argv.slice(2);
const outFlagIndex = args.indexOf("--out");
if (outFlagIndex !== -1 && args[outFlagIndex + 1] === undefined) {
  console.error("generate-prototype-fixtures: --out requires a path argument.");
  process.exit(1);
}
const outPath =
  outFlagIndex === -1 ? defaultOutPath : resolve(process.cwd(), args[outFlagIndex + 1]);

if (!existsSync(sourcePath)) {
  // Fail loud rather than emitting an empty global: a prototype that renders
  // nothing looks like a renderer bug, and the real cause would be silent.
  console.error(
    `Missing fixture source at ${sourcePath}\n` +
      "This script has exactly one input; it cannot invent one.\n",
  );
  process.exit(1);
}

const raw = readFileSync(sourcePath, "utf8");

let data;
try {
  data = JSON.parse(raw);
} catch (error) {
  console.error(`Fixture source is not valid JSON: ${sourcePath}\n${String(error)}\n`);
  process.exit(1);
}

// `JSON.stringify(_, null, 2)` is the whole transform. Key order is the source
// file's own insertion order, so the output is a pure function of the input --
// which is what lets the determinism test compare bytes rather than parse and
// deep-equal (a byte comparison also catches a stray trailing-newline change,
// which a deep-equal would happily ignore while `git diff` would not).
const banner = "// GENERATED by scripts/generate-prototype-fixtures.mjs — do not edit";
const body = `globalThis.CCC_FIXTURES = ${JSON.stringify(data, null, 2)};`;
const output = `${banner}\n${body}\n`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output, "utf8");

console.log(
  `fixtures.js regenerated: ${data.panels.length} panels, ` +
    `${Object.keys(data.screens).length} screens, ${output.length} bytes -> ${outPath}`,
);
